// Rebuild the vendored data packs in engine/kit/data/ from upstream checkouts.
//   RES=/path/to/checkouts node tools/build_data.mjs        (run from repo root)
// RES must contain:  gl-transitions/transitions/*.glsl   (github.com/gl-transitions/gl-transitions, per-file MIT/BSD)
//                    nice-color-palettes/1000.json        (github.com/Jam3/nice-color-palettes, MIT)
//                    open-color/open-color.json           (github.com/yeun/open-color, MIT)
//                    lucide/icons/*.svg + *.json           (github.com/lucide-icons/lucide, ISC)
// Output (plain JS globals, so pages work from file:// with no fetch):
//   engine/kit/data/gl_transitions.js  → window.GLT_SRC   {name:{author,license,desc,glsl}}
//   engine/kit/data/palettes.js        → window.NICE_PALETTES (1000×5 hex), window.OPEN_COLOR {hue:[10 shades]}
//   engine/kit/data/icons_lucide.js    → window.LUCIDE {name:[[d,len],…]}, window.LUCIDE_TAGS {name:"tags cats"}
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
const RES = process.env.RES || '/var/tmp/res', OUT = 'engine/kit/data';
mkdirSync(OUT, { recursive: true });
const banner = (what, lic, url) => `// GENERATED by tools/build_data.mjs — ${what}\n// Upstream: ${url} — licence: ${lic} (full text: resources/licenses/)\n`;

// ── 1 · gl-transitions (keep every file whose header licence is permissive: MIT / BSD) ──
{ const dir = join(RES, 'gl-transitions/transitions'), o = {}; const skipped = [];
  for (const f of readdirSync(dir).filter(f => f.endsWith('.glsl')).sort()) {
    const s = readFileSync(join(dir, f), 'utf8'), m = k => (s.match(new RegExp('//\\s*' + k + '\\s*:\\s*(.+)', 'i')) || [])[1]?.trim() || '';
    const lic = m('License');
    if (!/^(MIT|BSD)/i.test(lic)) { skipped.push(f + ' (' + (lic || 'none') + ')'); continue; }
    o[f.replace('.glsl', '')] = { author: m('Author'), license: lic, desc: m('Description') || m('Tags'), glsl: s };
  }
  writeFileSync(join(OUT, 'gl_transitions.js'), banner(Object.keys(o).length + ' GLSL transitions', 'MIT / BSD per file header (author+licence kept in every glsl)', 'https://github.com/gl-transitions/gl-transitions')
    + 'window.GLT_SRC = ' + JSON.stringify(o) + ';\n');
  console.log('gl-transitions', Object.keys(o).length, 'skipped', skipped); }

// ── 2 · palettes ──
{ const nice = JSON.parse(readFileSync(join(RES, 'nice-color-palettes/1000.json'), 'utf8'));
  const oc = JSON.parse(readFileSync(join(RES, 'open-color/open-color.json'), 'utf8')).theme?.colors || JSON.parse(readFileSync(join(RES, 'open-color/open-color.json'), 'utf8'));
  writeFileSync(join(OUT, 'palettes.js'), banner('1000 ColourLovers top palettes + Open Color', 'MIT (Jam3/nice-color-palettes) · MIT (yeun/open-color)', 'https://github.com/Jam3/nice-color-palettes · https://github.com/yeun/open-color')
    + 'window.NICE_PALETTES = ' + JSON.stringify(nice) + ';\nwindow.OPEN_COLOR = ' + JSON.stringify(oc) + ';\n');
  console.log('palettes', nice.length, Object.keys(oc).length); }

// ── 3 · lucide → per-element path data + exact lengths (measured in Chromium) ──
{ const dir = join(RES, 'lucide/icons'), names = readdirSync(dir).filter(f => f.endsWith('.svg')).map(f => f.slice(0, -4)).sort();
  const num = (a, k, d = 0) => { const m = a.match(new RegExp('\\b' + k + '="([^"]+)"')); return m ? +m[1] : d; };
  const toD = (tag, a) => {
    if (tag === 'path') return a.match(/\bd="([^"]+)"/)[1];
    if (tag === 'line') return `M${num(a, 'x1')} ${num(a, 'y1')}L${num(a, 'x2')} ${num(a, 'y2')}`;
    if (tag === 'polyline' || tag === 'polygon') { const p = a.match(/points="([^"]+)"/)[1].trim().split(/[\s,]+/).map(Number), q = [];
      for (let i = 0; i < p.length; i += 2) q.push((i ? 'L' : 'M') + p[i] + ' ' + p[i + 1]); return q.join('') + (tag === 'polygon' ? 'Z' : ''); }
    if (tag === 'circle' || tag === 'ellipse') { const cx = num(a, 'cx'), cy = num(a, 'cy'), rx = tag === 'circle' ? num(a, 'r') : num(a, 'rx'), ry = tag === 'circle' ? rx : num(a, 'ry');
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0Z`; }
    if (tag === 'rect') { const x = num(a, 'x'), y = num(a, 'y'), w = num(a, 'width'), h = num(a, 'height'); let rx = num(a, 'rx', NaN), ry = num(a, 'ry', NaN);
      if (isNaN(rx)) rx = isNaN(ry) ? 0 : ry; if (isNaN(ry)) ry = rx; rx = Math.min(rx, w / 2); ry = Math.min(ry, h / 2);
      if (!rx) return `M${x} ${y}h${w}v${h}h${-w}Z`;
      return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${-(w - 2 * rx)}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${-(h - 2 * ry)}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`; }
    return null; };
  const icons = {}, tags = {};
  for (const n of names) { const s = readFileSync(join(dir, n + '.svg'), 'utf8'), els = [];
    for (const m of s.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*)\/?>/g)) { const d = toD(m[1], m[2]); if (d) els.push(d); }
    icons[n] = els;
    const jf = join(dir, n + '.json'); if (existsSync(jf)) { const j = JSON.parse(readFileSync(jf, 'utf8')); tags[n] = [...(j.tags || []), ...(j.categories || [])].join(' '); } }
  const { chromium } = await import('playwright'); const b = await chromium.launch(), p = await b.newPage();
  const lens = await p.evaluate(icons => { const ns = 'http://www.w3.org/2000/svg', svg = document.createElementNS(ns, 'svg'), el = document.createElementNS(ns, 'path'); svg.appendChild(el); document.body.appendChild(svg);
    const o = {}; for (const [n, ds] of Object.entries(icons)) o[n] = ds.map(d => { el.setAttribute('d', d); return Math.round(el.getTotalLength() * 100) / 100; }); return o; }, icons);
  await b.close();
  const packed = {}; for (const n of names) packed[n] = icons[n].map((d, i) => [d, lens[n][i]]);
  writeFileSync(join(OUT, 'icons_lucide.js'), banner(names.length + ' Lucide icons (24×24, stroke 2, round caps) as [pathData, length] per element', 'ISC (Lucide Icons and Contributors)', 'https://github.com/lucide-icons/lucide')
    + 'window.LUCIDE = ' + JSON.stringify(packed) + ';\nwindow.LUCIDE_TAGS = ' + JSON.stringify(tags) + ';\n');
  console.log('lucide', names.length); }
